package org.apache.flink.python.util;

import org.apache.flink.api.common.typeinfo.Types;
import org.apache.flink.configuration.Configuration;
import org.apache.flink.configuration.PipelineOptions;
import org.apache.flink.streaming.api.datastream.DataStream;
import org.apache.flink.streaming.api.datastream.SingleOutputStreamOperator;
import org.apache.flink.streaming.api.environment.StreamExecutionEnvironment;
import org.apache.flink.streaming.api.functions.sink.v2.DiscardingSink;
import org.apache.flink.streaming.api.graph.StreamGraph;

import org.junit.jupiter.api.Test;

import java.util.Collections;

import static org.assertj.core.api.Assertions.assertThat;

/** A test class to test PythonConfigUtil getting executionEnvironment correctly. */
class PythonConfigUtilTest {

    @Test
    void testJobName() {
        String jobName = "MyTestJob";
        Configuration config = new Configuration();
        config.set(PipelineOptions.NAME, jobName);
        StreamExecutionEnvironment env = StreamExecutionEnvironment.getExecutionEnvironment(config);

        env.fromData(Collections.singletonList("test")).sinkTo(new DiscardingSink<>());
        StreamGraph streamGraph = env.getStreamGraph(true);
        assertThat(streamGraph.getJobName()).isEqualTo(jobName);
    }

    @Test
    void testHelperOperatorsGetUidsWhenAutoGeneratedUidsAreDisabled() throws Exception {
        StreamExecutionEnvironment env = StreamExecutionEnvironment.getExecutionEnvironment();
        env.getConfig().disableAutoGeneratedUIDs();
        DataStream<String> source = env.fromData("a", "b").uid("source");
        SingleOutputStreamOperator<String> keyBy =
                helper(source, PythonConfigUtil.STREAM_KEY_BY_MAP_OPERATOR_NAME);
        SingleOutputStreamOperator<String> secondKeyBy =
                helper(source, PythonConfigUtil.STREAM_KEY_BY_MAP_OPERATOR_NAME);
        SingleOutputStreamOperator<String> partitionCustom =
                helper(source, PythonConfigUtil.STREAM_PARTITION_CUSTOM_MAP_OPERATOR_NAME);
        // As in PyFlink, the values helper reads from the key-by helper through a partitioning.
        SingleOutputStreamOperator<String> values =
                helper(keyBy.keyBy(x -> x), PythonConfigUtil.KEYED_STREAM_VALUE_OPERATOR_NAME);
        values.union(secondKeyBy, partitionCustom).sinkTo(new DiscardingSink<>()).uid("sink");

        PythonConfigUtil.configPythonOperator(env);

        assertThat(keyBy.getTransformation().getUid()).isEqualTo("source-key-by");
        assertThat(secondKeyBy.getTransformation().getUid()).isEqualTo("source-key-by-2");
        assertThat(partitionCustom.getTransformation().getUid())
                .isEqualTo("source-partition-custom");
        assertThat(values.getTransformation().getUid()).isEqualTo("source-key-by-values");
        // Fails with "Auto generated UIDs have been disabled" if any operator lacks a uid.
        env.getStreamGraph();
    }

    @Test
    void testHelperOperatorsGetUidHashesWhenTheirInputOnlyHasOne() throws Exception {
        StreamExecutionEnvironment env = StreamExecutionEnvironment.getExecutionEnvironment();
        env.getConfig().disableAutoGeneratedUIDs();
        DataStream<String> source =
                env.fromData("a", "b").setUidHash("0123456789abcdef0123456789abcdef");
        SingleOutputStreamOperator<String> keyBy =
                helper(source, PythonConfigUtil.STREAM_KEY_BY_MAP_OPERATOR_NAME);
        SingleOutputStreamOperator<String> secondKeyBy =
                helper(source, PythonConfigUtil.STREAM_KEY_BY_MAP_OPERATOR_NAME);
        SingleOutputStreamOperator<String> values =
                helper(keyBy.keyBy(x -> x), PythonConfigUtil.KEYED_STREAM_VALUE_OPERATOR_NAME);
        values.union(secondKeyBy).sinkTo(new DiscardingSink<>()).uid("sink");

        PythonConfigUtil.configPythonOperator(env);

        // The same derivation as _derive_uid_hash in pyflink/datastream/data_stream.py.
        assertThat(keyBy.getTransformation().getUserProvidedNodeHash())
                .isEqualTo("19728c29abf67533e4dd6acdef9ae5e6");
        assertThat(secondKeyBy.getTransformation().getUserProvidedNodeHash())
                .isEqualTo("197fe28fcf4102d71cd8eddb76647af9");
        assertThat(values.getTransformation().getUserProvidedNodeHash())
                .isEqualTo("ffa1a88517fa195a542126da63d28d45");
        assertThat(keyBy.getTransformation().getUid()).isNull();
        env.getStreamGraph().getJobGraph();
    }

    @Test
    void testDerivedHelperOperatorUidHashesDoNotCollideIgnoringCase() throws Exception {
        StreamExecutionEnvironment env = StreamExecutionEnvironment.getExecutionEnvironment();
        env.getConfig().disableAutoGeneratedUIDs();
        DataStream<String> source =
                env.fromData("a", "b").setUidHash("0123456789abcdef0123456789abcdef");
        // The upper case form of the uid hash the key-by helper would otherwise get.
        source.map(x -> x)
                .returns(Types.STRING)
                .setUidHash("19728C29ABF67533E4DD6ACDEF9AE5E6")
                .sinkTo(new DiscardingSink<>())
                .uid("sink-1");
        SingleOutputStreamOperator<String> keyBy =
                helper(source, PythonConfigUtil.STREAM_KEY_BY_MAP_OPERATOR_NAME);
        keyBy.sinkTo(new DiscardingSink<>()).uid("sink-2");

        PythonConfigUtil.configPythonOperator(env);

        assertThat(keyBy.getTransformation().getUserProvidedNodeHash())
                .isEqualTo("197fe28fcf4102d71cd8eddb76647af9");
    }

    @Test
    void testHelperOperatorUidsAreLeftAloneWhenAutoGeneratedUidsAreEnabled() throws Exception {
        StreamExecutionEnvironment env = StreamExecutionEnvironment.getExecutionEnvironment();
        DataStream<String> source = env.fromData("a", "b").uid("source");
        SingleOutputStreamOperator<String> keyBy =
                helper(source, PythonConfigUtil.STREAM_KEY_BY_MAP_OPERATOR_NAME);
        keyBy.sinkTo(new DiscardingSink<>());

        PythonConfigUtil.configPythonOperator(env);

        assertThat(keyBy.getTransformation().getUid()).isNull();
    }

    @Test
    void testHelperOperatorUidIsNotDerivedOverAnExistingOneOrWithoutAnInputUid() throws Exception {
        StreamExecutionEnvironment env = StreamExecutionEnvironment.getExecutionEnvironment();
        env.getConfig().disableAutoGeneratedUIDs();
        SingleOutputStreamOperator<String> withUid =
                helper(
                                env.fromData("a").uid("source"),
                                PythonConfigUtil.STREAM_KEY_BY_MAP_OPERATOR_NAME)
                        .uid("own-uid");
        SingleOutputStreamOperator<String> withoutInputUid =
                helper(env.fromData("b"), PythonConfigUtil.STREAM_KEY_BY_MAP_OPERATOR_NAME);
        withUid.union(withoutInputUid).sinkTo(new DiscardingSink<>());

        PythonConfigUtil.configPythonOperator(env);

        assertThat(withUid.getTransformation().getUid()).isEqualTo("own-uid");
        assertThat(withoutInputUid.getTransformation().getUid()).isNull();
    }

    @Test
    void testDerivedHelperOperatorUidsDoNotCollide() throws Exception {
        StreamExecutionEnvironment env = StreamExecutionEnvironment.getExecutionEnvironment();
        env.getConfig().disableAutoGeneratedUIDs();
        DataStream<String> source = env.fromData("a", "b").uid("source");
        source.map(x -> x)
                .returns(Types.STRING)
                .uid("source-key-by")
                .sinkTo(new DiscardingSink<>())
                .uid("sink-1");
        SingleOutputStreamOperator<String> keyBy =
                helper(source, PythonConfigUtil.STREAM_KEY_BY_MAP_OPERATOR_NAME);
        keyBy.sinkTo(new DiscardingSink<>()).uid("sink-2");

        PythonConfigUtil.configPythonOperator(env);

        // A branch added after the job was configured once, e.g. by get_execution_plan().
        SingleOutputStreamOperator<String> laterKeyBy =
                helper(source, PythonConfigUtil.STREAM_KEY_BY_MAP_OPERATOR_NAME);
        laterKeyBy.sinkTo(new DiscardingSink<>()).uid("sink-3");

        PythonConfigUtil.configPythonOperator(env);

        assertThat(keyBy.getTransformation().getUid()).isEqualTo("source-key-by-2");
        assertThat(laterKeyBy.getTransformation().getUid()).isEqualTo("source-key-by-3");
        // Fails on duplicate uids.
        env.getStreamGraph().getJobGraph();
    }

    private static SingleOutputStreamOperator<String> helper(
            DataStream<String> input, String name) {
        return input.map(x -> x).returns(Types.STRING).name(name);
    }
}
